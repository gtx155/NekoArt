int hash_num(int n) {
    unsigned int knuth_constant = 2654435761;
    return (n * knuth_constant) % 10 + 1;
}

char* get_time() {
    static char date_string[20];
    time_t current_time;
    struct tm *local_time;

    time(&current_time);
    local_time = localtime(&current_time);
    strftime(date_string, sizeof(date_string), "%Y_%m_%d-%H_%M_%S", local_time);

    return date_string;
}

int save_file(char *text_art, char *text_msg) {
    printf("Saving...\n");

    char file_name[37];
    sprintf(file_name, "NekoArt-%s.txt", get_time());

    FILE *fptr = fopen(file_name, "w");

    fprintf(fptr, "%s\n%s", text_art, text_msg);
    fclose(fptr);

    return 0;
}

